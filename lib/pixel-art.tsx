export function PixelFoodArt({
  craving,
  size = 96,
}: {
  craving: CravingId;
  size?: number;
}) {
  const palette = PALETTES[craving];
  const grid = SPRITES[craving];
  const cell = size / 16;

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      className="pixel-art"
      aria-hidden
      style={{ imageRendering: "pixelated" }}
    >
      {grid.map((row, y) =>
        row.map((colorIndex, x) => {
          if (!colorIndex) return null;
          return (
            <rect
              key={`${x}-${y}`}
              x={x * cell}
              y={y * cell}
              width={cell}
              height={cell}
              fill={palette[colorIndex - 1]}
              shapeRendering="crispEdges"
            />
          );
        }),
      )}
    </svg>
  );
}
